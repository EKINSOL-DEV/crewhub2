/* The generator of models/index.ts (round 71, seam 1): the style's data models as a static list of JSON imports, in
   place of Vite's `import.meta.glob` over ../models/*.json, so the style's index (and every module whose chain reaches
   it: world/style.ts, state/runtimes.ts, state/build.ts, world/TownScene.ts) loads in Node as well as in Vite. Run it
   after adding, renaming or removing a model file:

     node packages/style-greenhouse/scripts/models-index.ts

   test/modelIndex.test.ts holds the written file to this generator and to the folder's contents. The names are the
   file names without `.json` (`<key>` or `<key>.<variant>`), as the glob's keys were, in code-unit order. */
import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

/** The style package's root folder. */
export const PACKAGE_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** The model names of a package root's `models` folder: its `.json` files without the extension, in code-unit order (`sort()`'s own). */
export function modelNames(root: string): string[] {
  return readdirSync(path.join(root, "models"))
    .filter((file) => file.endsWith(".json"))
    .map((file) => file.slice(0, -".json".length))
    .sort();
}

/** The text of models/index.ts for these names. */
export function render(names: readonly string[]): string {
  const lines = [
    "/* Generated by scripts/models-index.ts from the .json files of this folder: do not edit by hand. Run",
    "   `node packages/style-greenhouse/scripts/models-index.ts` after adding, renaming or removing a model; the test",
    "   test/modelIndex.test.ts fails until the list matches the folder. A static list in place of Vite's import.meta.glob",
    "   (round 71), so the style loads in Node; the names are the file names without `.json`, as the glob's keys were. */",
  ];
  names.forEach((name, i) => lines.push(`import m${i} from "./${name}.json" with { type: "json" };`));
  lines.push("");
  lines.push("/** Every data model's parsed JSON by name (`<key>` or `<key>.<variant>`), validated on first use by src/models.ts. */");
  lines.push("export const modelFiles: ReadonlyMap<string, unknown> = new Map<string, unknown>([");
  names.forEach((name, i) => lines.push(`  ["${name}", m${i}],`));
  lines.push("]);");
  lines.push("");
  return lines.join("\n");
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const names = modelNames(PACKAGE_ROOT);
  const target = path.join(PACKAGE_ROOT, "models", "index.ts");
  writeFileSync(target, render(names));
  console.log(`${path.relative(process.cwd(), target)}: ${names.length} models`);
}
